/**
 * Build-time security policy for the browser app.
 *
 * One source of truth feeds two delivery channels:
 *  - `<meta http-equiv="Content-Security-Policy">` injected into every built
 *    HTML page, so the policy applies on any static host;
 *  - a `_headers` file (Netlify / Cloudflare Pages format) carrying the same
 *    CSP plus the headers a meta tag cannot express (frame-ancestors, nosniff,
 *    referrer/permissions policy, cache rules). Hosts that ignore `_headers`
 *    must replicate it in their own configuration.
 *
 * Third-party origins are only added when the feature that needs them is
 * configured (Google sign-in, Google Analytics, an absolute API origin).
 */

import { loadEnv } from 'vite';

const originOf = (value) => {
  try {
    return new URL(value).origin;
  } catch {
    return null; // relative ("/api") → same origin, covered by 'self'
  }
};

/**
 * @param {Record<string, string>} env - VITE_* environment values
 * @returns {{ meta: string, header: string }} policy strings
 */
export function buildContentSecurityPolicy(env = {}) {
  const apiOrigin = originOf(env.VITE_API_BASE_URL);
  const socketOrigin = originOf(env.VITE_SOCKET_URL);
  const analytics = Boolean(env.VITE_GA_MEASUREMENT_ID);
  const googleSignIn = Boolean(env.VITE_GOOGLE_CLIENT_ID);

  const socketWs = socketOrigin
    ? [socketOrigin.replace(/^http/, 'ws')]
    : [];

  const directives = {
    'default-src': ["'self'"],
    'script-src': [
      "'self'",
      ...(analytics ? ['https://www.googletagmanager.com'] : []),
      ...(googleSignIn ? ['https://accounts.google.com/gsi/client'] : [])
    ],
    // React/Leaflet set inline style attributes; stylesheets come from Google
    // Fonts and the (SRI-pinned) Leaflet CSS on unpkg.
    'style-src': [
      "'self'",
      "'unsafe-inline'",
      'https://fonts.googleapis.com',
      'https://unpkg.com',
      ...(googleSignIn ? ['https://accounts.google.com/gsi/style'] : [])
    ],
    'font-src': ["'self'", 'https://fonts.gstatic.com'],
    'img-src': [
      "'self'",
      'data:',
      'blob:',
      'https://*.tile.openstreetmap.org',
      'https://unpkg.com',
      ...(analytics ? ['https://www.google-analytics.com', 'https://www.googletagmanager.com'] : [])
    ],
    'connect-src': [
      "'self'",
      ...(apiOrigin ? [apiOrigin] : []),
      ...(socketOrigin ? [socketOrigin, ...socketWs] : []),
      ...(analytics
        ? [
            'https://www.google-analytics.com',
            'https://*.google-analytics.com',
            'https://*.analytics.google.com',
            'https://www.googletagmanager.com'
          ]
        : []),
      ...(googleSignIn ? ['https://accounts.google.com/gsi/'] : [])
    ],
    'frame-src': googleSignIn ? ['https://accounts.google.com/gsi/'] : ["'none'"],
    'worker-src': ["'self'"],
    'manifest-src': ["'self'"],
    'object-src': ["'none'"],
    'base-uri': ["'self'"],
    'form-action': ["'self'"]
  };

  const serialize = (entries) =>
    Object.entries(entries)
      .map(([name, values]) => `${name} ${[...new Set(values)].join(' ')}`)
      .join('; ');

  return {
    // frame-ancestors is ignored in <meta>, so it only travels in the header
    meta: serialize(directives),
    header: serialize({ ...directives, 'frame-ancestors': ["'none'"] })
  };
}

/**
 * @param {string} cspHeader
 * @returns {string} contents of the `_headers` file
 */
export function buildHeadersFile(cspHeader) {
  return `# Generated by vite-plugins/securityHeaders.js — do not edit by hand.
# Netlify / Cloudflare Pages format. Other hosts: replicate these headers.
/*
  Content-Security-Policy: ${cspHeader}
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: geolocation=(), camera=(), microphone=(), payment=(), usb=()
  Cross-Origin-Opener-Policy: same-origin
  # Enable only once the domain is committed to HTTPS (browsers cache it):
  # Strict-Transport-Security: max-age=15552000; includeSubDomains

/assets/*
  Cache-Control: public, max-age=31536000, immutable

/sw.js
  Cache-Control: no-cache

/manifest.json
  Cache-Control: no-cache
`;
}

export default function securityHeadersPlugin() {
  let policy = null;

  return {
    name: 'sscc-security-headers',
    apply: 'build',

    configResolved(config) {
      const env = loadEnv(config.mode, config.envDir || process.cwd(), 'VITE_');
      policy = buildContentSecurityPolicy(env);
    },

    transformIndexHtml: {
      order: 'post',
      // Placed straight after <meta charset> (which must stay within the first
      // 1024 bytes) and before every script/style tag, so it governs them all.
      handler(html) {
        const tag = `<meta http-equiv="Content-Security-Policy" content="${policy.meta}" />`;
        const charset = html.match(/<meta\s+charset=[^>]*>/i);
        if (charset) return html.replace(charset[0], `${charset[0]}\n    ${tag}`);
        return html.replace(/<head[^>]*>/i, (open) => `${open}\n    ${tag}`);
      }
    },

    generateBundle() {
      this.emitFile({
        type: 'asset',
        fileName: '_headers',
        source: buildHeadersFile(policy.header)
      });
    }
  };
}
